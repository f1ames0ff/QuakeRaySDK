// FSR 3.1 shader permutation generator for Linux.
//
// The Windows FidelityFX SDK ships FidelityFX_SC.exe, which compiles the GLSL
// shaders with glslangValidator and writes the *_permutations.h headers that
// ffx_fsr3upscaler_shaderblobs.cpp includes. This driver performs the same job
// with a Linux glslangValidator: it compiles every permutation, de-duplicates
// identical binaries by hash, and emits the same indirection table format.

#include "glsl_compiler.h"

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <unordered_map>
#include <vector>

static const char *const kOptions[] = {
    "FFX_FSR3UPSCALER_OPTION_REPROJECT_USE_LANCZOS_TYPE",
    "FFX_FSR3UPSCALER_OPTION_HDR_COLOR_INPUT",
    "FFX_FSR3UPSCALER_OPTION_LOW_RESOLUTION_MOTION_VECTORS",
    "FFX_FSR3UPSCALER_OPTION_JITTERED_MOTION_VECTORS",
    "FFX_FSR3UPSCALER_OPTION_INVERTED_DEPTH",
    "FFX_FSR3UPSCALER_OPTION_APPLY_SHARPENING",
};

static void WritePermutationKey(FILE *fp, const std::string &name)
{
    std::fprintf(fp, "typedef union %s_PermutationKey {\n", name.c_str());
    std::fprintf(fp, "    struct {\n");
    for (const char *option : kOptions)
    {
        std::fprintf(fp, "        uint32_t %s : 1;\n", option);
    }
    std::fprintf(fp, "    };\n");
    std::fprintf(fp, "    uint32_t index;\n");
    std::fprintf(fp, "} %s_PermutationKey;\n\n", name.c_str());
}

static void WritePermutationInfoStruct(FILE *fp, const std::string &name)
{
    std::fprintf(fp, "typedef struct %s_PermutationInfo {\n", name.c_str());
    std::fprintf(fp, "    const uint32_t       blobSize;\n");
    std::fprintf(fp, "    const unsigned char* blobData;\n\n");
    std::fprintf(fp, "    const uint32_t  numConstantBuffers;\n");
    std::fprintf(fp, "    const char**    constantBufferNames;\n");
    std::fprintf(fp, "    const uint32_t* constantBufferBindings;\n");
    std::fprintf(fp, "    const uint32_t* constantBufferCounts;\n");
    std::fprintf(fp, "    const uint32_t* constantBufferSpaces;\n\n");
    std::fprintf(fp, "    const uint32_t  numSRVTextures;\n");
    std::fprintf(fp, "    const char**    srvTextureNames;\n");
    std::fprintf(fp, "    const uint32_t* srvTextureBindings;\n");
    std::fprintf(fp, "    const uint32_t* srvTextureCounts;\n");
    std::fprintf(fp, "    const uint32_t* srvTextureSpaces;\n\n");
    std::fprintf(fp, "    const uint32_t  numUAVTextures;\n");
    std::fprintf(fp, "    const char**    uavTextureNames;\n");
    std::fprintf(fp, "    const uint32_t* uavTextureBindings;\n");
    std::fprintf(fp, "    const uint32_t* uavTextureCounts;\n");
    std::fprintf(fp, "    const uint32_t* uavTextureSpaces;\n\n");
    std::fprintf(fp, "    const uint32_t  numSRVBuffers;\n");
    std::fprintf(fp, "    const char**    srvBufferNames;\n");
    std::fprintf(fp, "    const uint32_t* srvBufferBindings;\n");
    std::fprintf(fp, "    const uint32_t* srvBufferCounts;\n");
    std::fprintf(fp, "    const uint32_t* srvBufferSpaces;\n\n");
    std::fprintf(fp, "    const uint32_t  numUAVBuffers;\n");
    std::fprintf(fp, "    const char**    uavBufferNames;\n");
    std::fprintf(fp, "    const uint32_t* uavBufferBindings;\n");
    std::fprintf(fp, "    const uint32_t* uavBufferCounts;\n");
    std::fprintf(fp, "    const uint32_t* uavBufferSpaces;\n\n");
    std::fprintf(fp, "    const uint32_t  numSamplers;\n");
    std::fprintf(fp, "    const char**    samplerNames;\n");
    std::fprintf(fp, "    const uint32_t* samplerBindings;\n");
    std::fprintf(fp, "    const uint32_t* samplerCounts;\n");
    std::fprintf(fp, "    const uint32_t* samplerSpaces;\n\n");
    std::fprintf(fp, "    const uint32_t  numRTAccelerationStructures;\n");
    std::fprintf(fp, "    const char**    rtAccelerationStructureNames;\n");
    std::fprintf(fp, "    const uint32_t* rtAccelerationStructureBindings;\n");
    std::fprintf(fp, "    const uint32_t* rtAccelerationStructureCounts;\n");
    std::fprintf(fp, "    const uint32_t* rtAccelerationStructureSpaces;\n");
    std::fprintf(fp, "} %s_PermutationInfo;\n\n", name.c_str());
}

static void WritePermutationHeader(FILE *fp, GLSLCompiler &compiler, const Permutation &permutation)
{
    std::fprintf(fp, "// %s.h.\n", permutation.name.c_str());
    std::fprintf(fp, "// Auto generated by FidelityFX-SC (Linux source build).\n\n");

    GLSLShaderBinary *binary = dynamic_cast<GLSLShaderBinary *>(permutation.shaderBinary.get());
    if (binary == nullptr)
    {
        return;
    }

    const uint32_t size = (uint32_t)binary->BufferSize();
    std::fprintf(fp, "static const uint32_t g_%s_size = %u;\n\n", permutation.name.c_str(), size);
    std::fprintf(fp, "static const unsigned char g_%s_data[] = {\n", permutation.name.c_str());
    const uint8_t *data = binary->BufferPointer();
    for (uint32_t i = 0; i < size; ++i)
    {
        std::fprintf(fp, "0x%02x%s", data[i], (i + 1) % 16 == 0 ? ",\n" : ",");
    }
    std::fprintf(fp, "\n};\n\n");

    std::mutex writeMutex;
    compiler.WriteBinaryHeaderReflectionData(fp, permutation, writeMutex);
}

int main(int argc, char **argv)
{
    if (argc != 7)
    {
        std::fprintf(stderr,
            "usage: %s <glslangValidator> <shader.glsl> <permutation-name> <outdir> <half> <gpu-include-dir>\n",
            argv[0]);
        return 2;
    }

    const std::string glslang = argv[1];
    const std::string shader = argv[2];
    const std::string name = argv[3];
    const std::string outDir = argv[4];
    const int half = std::atoi(argv[5]);
    const std::string gpuInclude = argv[6];

    fs::create_directories(outDir);
    GLSLCompiler compiler(glslang, shader, name, fs::path(shader).filename().string(),
                          outDir, false, false);

    std::vector<Permutation> uniquePermutations;
    std::unordered_map<std::string, int> hashToIndex;
    int keyToIndex[64];

    for (int key = 0; key < 64; ++key)
    {
        Permutation permutation;
        permutation.key = (uint32_t)key;
        permutation.sourcePath = shader;

        std::vector<std::string> args = {
            "-V", "--target-env", "vulkan1.2", "-S", "comp", "-Os",
            "-DFFX_GLSL=1", "-DFFX_GPU=1",
            std::string("-DFFX_HALF=") + std::to_string(half),
            "-DFFX_FSR3UPSCALER_OPTION_UPSAMPLE_SAMPLERS_USE_DATA_HALF=0",
            "-DFFX_FSR3UPSCALER_OPTION_ACCUMULATE_SAMPLERS_USE_DATA_HALF=0",
            "-DFFX_FSR3UPSCALER_OPTION_REPROJECT_SAMPLERS_USE_DATA_HALF=1",
            "-DFFX_FSR3UPSCALER_OPTION_POSTPROCESSLOCKSTATUS_SAMPLERS_USE_DATA_HALF=0",
            "-DFFX_FSR3UPSCALER_OPTION_UPSAMPLE_USE_LANCZOS_TYPE=2",
            "-I" + gpuInclude,
            "-I" + gpuInclude + "/fsr3upscaler",
        };

        for (int i = 0; i < 6; ++i)
        {
            args.push_back(std::string("-D") + kOptions[i] + "=" + (((key >> i) & 1) ? "1" : "0"));
        }

        std::mutex writeMutex;
        if (!compiler.Compile(permutation, args, writeMutex))
        {
            std::fprintf(stderr, "compile failed: %s key %d\n", name.c_str(), key);
            return 1;
        }
        if (!compiler.ExtractReflectionData(permutation))
        {
            std::fprintf(stderr, "reflection failed: %s key %d\n", name.c_str(), key);
            return 1;
        }

        auto it = hashToIndex.find(permutation.hashDigest);
        if (it == hashToIndex.end())
        {
            const int index = (int)uniquePermutations.size();
            hashToIndex.emplace(permutation.hashDigest, index);
            keyToIndex[key] = index;
            uniquePermutations.push_back(permutation);
        }
        else
        {
            keyToIndex[key] = it->second;
        }
    }

    for (const Permutation &permutation : uniquePermutations)
    {
        const std::string path = outDir + "/" + permutation.name + ".h";
        FILE *fp = std::fopen(path.c_str(), "wb");
        if (fp == nullptr)
        {
            std::fprintf(stderr, "cannot write %s\n", path.c_str());
            return 1;
        }
        WritePermutationHeader(fp, compiler, permutation);
        std::fclose(fp);
    }

    const std::string finalPath = outDir + "/" + name + "_permutations.h";
    FILE *fp = std::fopen(finalPath.c_str(), "wb");
    if (fp == nullptr)
    {
        std::fprintf(stderr, "cannot write %s\n", finalPath.c_str());
        return 1;
    }

    for (const Permutation &permutation : uniquePermutations)
    {
        std::fprintf(fp, "#include \"%s.h\"\n", permutation.name.c_str());
    }
    std::fprintf(fp, "\n");

    WritePermutationKey(fp, name);
    WritePermutationInfoStruct(fp, name);

    std::fprintf(fp, "static const uint32_t g_%s_IndirectionTable[] = {\n", name.c_str());
    for (int key = 0; key < 64; ++key)
    {
        std::fprintf(fp, "    %d,\n", keyToIndex[key]);
    }
    std::fprintf(fp, "};\n\n");

    std::fprintf(fp, "static const %s_PermutationInfo g_%s_PermutationInfo[] = {\n", name.c_str(), name.c_str());
    for (const Permutation &permutation : uniquePermutations)
    {
        std::fprintf(fp, "    { g_%s_size, g_%s_data, ", permutation.name.c_str(), permutation.name.c_str());
        compiler.WritePermutationHeaderReflectionData(fp, permutation);
        std::fprintf(fp, "},\n");
    }
    std::fprintf(fp, "};\n\n");

    std::fclose(fp);
    std::printf("wrote %s: %zu unique permutations\n", finalPath.c_str(), uniquePermutations.size());
    return 0;
}
